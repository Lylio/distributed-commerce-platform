import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('real order publication and processing stream live, trace, reload and recover without duplicates', async ({ page, context }) => {
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#/monitor');
  await expect(page.getByRole('heading', { name: 'System monitor.' })).toBeVisible();
  await expect(page.locator('.monitor-connection')).toContainText('Live');
  const inventory = await (await page.request.get('/api/inventory')).json();
  const product = inventory.find((item: { availableQuantity: number }) => item.availableQuantity > 10).productId;
  const response = await page.request.post('/api/orders', { data: { customerId: randomUUID(), items: [{ productId: product, quantity: 1 }] } });
  expect(response.ok()).toBeTruthy();
  const id = (await response.json()).id;
  await expect(page.locator('.monitor-table tbody tr').filter({ hasText: id.slice(0, 8) }).first()).toBeVisible();
  await page.getByLabel('Order ID').fill(id);
  await expect(page.locator('.monitor-table').getByText('OrderCreatedEvent', { exact: true }).first()).toBeVisible();
  await expect(page.locator('.monitor-table').getByText('PaymentResultEvent', { exact: true }).first()).toBeVisible();
  await expect.poll(async () => (await (await page.request.get(`/api/orders/${id}/details`)).json()).order.status).toMatch(/CONFIRMED|CANCELLED/);
  await expect(page.locator('.trace-summary strong')).toHaveText(/Order confirmed|Order cancelled/);
  await page.getByLabel('Event type').selectOption('PaymentResultEvent');
  await expect(page.locator('.monitor-table tbody tr').first()).toContainText('PaymentResultEvent');
  await page.getByLabel('Event type').selectOption('');
  await page.screenshot({ path: 'test-results/monitor-desktop.png', fullPage: true });
  await context.setOffline(true);
  await expect(page.locator('.monitor-connection')).toContainText('Reconnecting', { timeout: 40000 });
  await context.setOffline(false);
  await expect(page.locator('.monitor-connection')).toContainText('Live');
  const labels = await page.getByRole('button', { name: /^Inspect observation / }).evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')));
  expect(new Set(labels).size).toBe(labels.length);
  await page.reload();
  await page.getByLabel('Order ID').fill(id);
  await expect(page.locator('.monitor-table').getByText('OrderCreatedEvent', { exact: true }).first()).toBeVisible();
  await expect(page.locator('.monitor-table').getByText(/History/).first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/monitor-mobile.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('forced payment failure traces real cancellation and committed inventory release', async ({ page }) => {
  test.skip(process.env.MONITOR_FORCE_FAILURE !== 'true', 'Requires DEMO_PAYMENT_FORCE_FAILURE=true in Compose');
  await page.goto('/#/monitor');
  await expect(page.locator('.monitor-connection')).toContainText('Live');
  const inventory = await (await page.request.get('/api/inventory')).json();
  const product = inventory.find((item: { availableQuantity: number }) => item.availableQuantity > 0).productId;
  const before = inventory.find((item: { productId: string }) => item.productId === product);
  const response = await page.request.post('/api/orders', { data: { customerId: randomUUID(), items: [{ productId: product, quantity: 1 }] } });
  const id = (await response.json()).id;
  await page.getByLabel('Order ID').fill(id);
  await expect(page.locator('.trace-summary strong')).toHaveText('Order cancelled');
  await expect(page.getByText('Inventory release committed. Reserved stock was restored.')).toBeVisible();
  await expect(page.locator('.monitor-table').getByText('OrderCancelledEvent', { exact: true }).first()).toBeVisible();
  await expect(page.locator('.monitor-table').getByText('InventoryReleased', { exact: true })).toBeVisible();
  const details = await (await page.request.get(`/api/orders/${id}/details`)).json();
  expect(details.paymentStatus).toBe('FAILED');
  const after = (await (await page.request.get('/api/inventory')).json()).find((item: { productId: string }) => item.productId === product);
  expect(after).toEqual(before);
  await page.screenshot({ path: 'test-results/monitor-compensation.png', fullPage: true });
});
